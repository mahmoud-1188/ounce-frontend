const PURITY = { 24: 1, 22: 22 / 24, 21: 21 / 24, 18: 18 / 24, 14: 14 / 24 };
// وجهات سحب الذهب من الخزنة. المشغول يخرج للعرض في المحل، والخام (وهو
// الكسر) يخرج لسداد مورد. تسجيل الوجهة يمنع اختفاء وزن من الخزنة بلا
// وجهة معروفة — وهو أكثر ما يصعب تتبّعه لاحقًا.

const fine24 = (w, karat) => (Number(w) || 0) * (PURITY[karat] || Number(karat) / 24);

const fmt = (n, d = 2) =>
  (Number.isFinite(n) ? n : 0).toLocaleString("en-US", {
    minimumFractionDigits: d,
    maximumFractionDigits: d,
  });

// ── الوزن يُعرض بثلاث خانات دائمًا ──
//
// «الملي» في سوق الذهب جزء من ألف من الجرام، وله ثمن: بسعر 500 للجرام
// يساوي نصف ريال. عرض 1.001 جم كـ«1.00» يُخفي مليًا في كل قطعة، فيظهر
// الفرق عند الجرد بلا مصدر.
//
// ولا يقتصر الأمر على العرض: الوزن يُخزَّن ويُحسب بثلاث خانات كذلك،
// فالتقريب لخانتين قبل الضرب في السعر يُضيع القيمة لا العرض فقط.
// ── عرض النقد ──
//
// ⚠ الهللات تُعرض دائمًا في المبالغ التي تُدفع أو تُستحق.
//
// إجمالي 1,040.30 معروضًا «1,040» يجعل المستخدم يقارن رقمًا برقم فلا
// يتطابقان، فيظن الحساب خاطئًا وهو سليم. والفرق يتراكم عبر الفواتير.
//
// الاختصار (بلا هللات) يبقى مسموحًا في الملخّصات والرسوم حيث الترتيب
// أهمّ من الدقة — لكن ليس فيما يُدفع.

// ═══════════════════════════════════════════════════════════════════════
//  الحساب الدقيق — بالوحدات الصغرى صحيحةً
//
//  ⚠ الأعداد العائمة تُخطئ في المال والوزن.
//
//    0.1 + 0.2              = 0.30000000000000004
//    Math.round(1.005*100)/100 = 1        بدل 1.01
//    100 × 12.345           = 1234.500000000002
//    4.35 * 100             = 434.99999999999994
//
//  الهللة تضيع، ثم تتراكم عبر آلاف الأسطر فيظهر فرقٌ في الميزان لا
//  مصدر له — يبحث عنه المحاسب في المستندات وهو في الحساب نفسه.
//
//  الحل: نحسب بالوحدة الصغرى **صحيحةً**. المال بالهللات والوزن
//  بالمليّات. الأعداد الصحيحة في JavaScript دقيقة حتى 2^53، وهو أكبر
//  من أي رصيد محل.
// ═══════════════════════════════════════════════════════════════════════

/// ⚠ التحويل يمرّ بالنصّ لا بالضرب: `4.35 * 100` يعطي 434.99999999999994
/// فيُقرَّب لـ434 وتضيع هللة. والنصّ يعطي 435 بالضبط.

function toMinor(value, places) {
  if (value == null || value === "") return 0;

  // ⚠ النصّ يُقرأ حرفيًا لا عبر Number.
  //
  // الحقول تُعطي نصًّا، وتحويله لعائم يُفسده قبل أن نراه: «1.005» تصير
  // 1.00499999999999989 فتُقرَّب لـ1.00 وتضيع هللة. وقراءة الأرقام
  // كما كُتبت تُعطي 101 بالضبط.
  if (typeof value === "string") {
    const t = value.trim();
    const m = t.match(/^(-?)(\d*)(?:[.,](\d*))?$/);
    if (m) {
      const [, sign, whole = "0", frac = ""] = m;
      // خانة زائدة واحدة للتقريب المصرفي
      const kept = frac.slice(0, places);
      const next = frac.charCodeAt(places) - 48;
      let n = Number((whole || "0") + kept.padEnd(places, "0"));
      if (next >= 5) n += 1;
      return sign === "-" ? -n : n;
    }
  }

  const n = Number(value);
  if (!Number.isFinite(n)) return 0;
  const neg = n < 0;
  // العائم: نُثبّت الخانات ثم نُزيل الفاصلة — بلا ضرب عائم
  const fixed = Math.abs(n).toFixed(places);
  const [whole, frac = ""] = fixed.split(".");
  const digits = (whole + frac.padEnd(places, "0")).replace(/^0+(?=\d)/, "");
  const out = Number(digits || "0");
  return neg ? -out : out;
}

/// يُعيد الوحدة الصغرى إلى رقم عشري.

function fromMinor(minor, places) {
  const n = Math.trunc(Number(minor) || 0);
  const div = 10 ** places;
  return n / div;
}

// ── المال: بالهللات ──

const halalas = (v) => toMinor(v, 2);

const fromHalalas = (h) => fromMinor(h, 2);

// ── الوزن: بالمليّات ──

const millis = (v) => toMinor(v, 3);

const fromMillis = (m) => fromMinor(m, 3);

/// جمع مبالغ بلا انحراف: نجمع الهللات صحيحةً ثم نعود.
///
/// ⚖ الفرق ليس نظريًا: جمع 12.345 مئة مرة بالعائم يعطي
/// 1234.500000000002، وبالمليّات يعطي 1234.500 بالضبط.

const sumMoney = (arr, get = (x) => x) =>
  fromHalalas((arr || []).reduce((a, x) => a + halalas(get(x)), 0));

const sumWeight = (arr, get = (x) => x) =>
  fromMillis((arr || []).reduce((a, x) => a + millis(get(x)), 0));

/// ضرب وزن في سعر — النتيجة مال.
///
/// ⚠ نضرب المليّات في الهللات ثم نقسم على ألف، فلا يدخل عائمٌ في
/// المنتصف. القسمة الأخيرة وحدها تُقرَّب، ومرة واحدة لا مرتين.

function weightTimesPrice(weight, pricePerGram) {
  const w = millis(weight);           // ×1000
  const p = halalas(pricePerGram);    // ×100
  // w*p بوحدة 10^5 — نُريد 10^2
  return fromHalalas(Math.round((w * p) / 1000));
}

/// قسمة مبلغ على وزن — النتيجة سعر جرام بأربع خانات.

function priceFromTotal(total, weight) {
  const w = millis(weight);
  if (w === 0) return 0;
  const t = halalas(total);
  // t/w بوحدة 10^-1 — نُريد أربع خانات
  return Math.round((t * 1000 * 100) / w) / 10000;
}

/// نسبة من مبلغ — الضريبة مثلًا.

const percentOf = (amount, rate) =>
  fromHalalas(Math.round(halalas(amount) * Number(rate || 0)));

