/// تقريب وزني موحّد — كل وزن يمرّ منه قبل الحفظ.

const roundW = (v) => {
  // ⚠ يمرّ بالمليّات صحيحةً: `Math.round(v*1000)/1000` يُخطئ حين يكون
  // v عائمًا مكسورًا — 12.345 يصير 12.344999… فيُقرَّب لـ12.344.
  return fromMillis(millis(v));
};

/// قيمة الوزن نقدًا بلا تقريب وسيط: نضرب الوزن الكامل في السعر ثم
/// نقرّب النتيجة لخانتين. التقريب قبل الضرب يُضيع الملي.

const weightValue = (weight, pricePerG) =>
  Math.round((Number(weight) || 0) * (Number(pricePerG) || 0) * 100) / 100;

/// عرض الوزن بالجرام والملي: «1.500 جم (1 جم و500 ملي)»

const fmtWLong = (n) => {
  const w = roundW(n);
  const g = Math.floor(w);
  const mg = Math.round((w - g) * 1000);
  if (mg === 0) return `${fmtW(w)} جم`;
  return `${fmtW(w)} جم (${g} جم و${mg} ملي)`;
};

