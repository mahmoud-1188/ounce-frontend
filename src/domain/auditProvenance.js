function auditProvenance(index) {
  const ids = new Set();
  index.forEach((r) => { ids.add(r.id); if (r.ref) ids.add(r.ref); });
  const broken = [];
  index.forEach((r) => {
    (r.links || []).forEach((l) => {
      if (l && !ids.has(l)) broken.push({ ref: r.ref, kind: r.kind, missing: l });
    });
  });
  const noSource = index.filter(
    (r) => ["cash", "expense"].includes(r.kind) && !r.category && !(r.links || []).length
  );
  return { broken, noSource, total: index.length };
}


