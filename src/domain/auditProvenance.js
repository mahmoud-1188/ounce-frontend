//  مطابقة إيداعات الشبكة مع كشف البنك
//
//  البنك لا يودع كل عملية على حدة: يجمع عمليات اليوم في **إيداع واحد**
//  بعد خصم عمولته. فمطابقة عملية بعملية تفشل دائمًا، والمطابقة الصحيحة
//  واحد-إلى-عدة: إيداع بنكي واحد يقابل مجموعة عمليات محلية.
//
//  ثلاث حالات لا رابع لها:
//    ① مطابق      — ظهر في البنك وطابق النظام
//    ② في الطريق  — سُجّل عندك ولم يصل البنك بعد
//    ③ غير مسجّل  — ظهر في البنك ولا مقابل له عندك
//
//  الحالة الثالثة أخطرها: عمولة خصمها البنك ولم تُقيَّد، أو إيداع لست
//  مصدره. تركها بلا فحص يجعل رصيدك الدفتري يخالف البنك بلا تفسير.
// ═══════════════════════════════════════════════════════════════════════

