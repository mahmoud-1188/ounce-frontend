const normAr = (t) =>
  String(t || "")
    .toLowerCase()
    .replace(/[\u064B-\u0652\u0670]/g, "")   // التشكيل
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    // ⚠ علامات الترقيم العربية داخل نطاق الحروف العربية نفسه: «؟» و«،»
    // و«؛» تنجو من التصفية، فتصير «كسر؟» كلمةً فيُقطع أولها بالخطأ.
    .replace(/[\u060C\u061B\u061F\u066A-\u066D\u06D4]/g, " ")
    .replace(/[^\u0600-\u06FF\w\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/// يُجرّد الكلمة من بادئات الجرّ والتعريف — «بالمخزون» تطابق «مخزون».

export { normAr };
