const stemAr = (w) => {
  let x = w;
  x = x.replace(/^(وال|بال|كال|فال|لل|ال)/, "");
  x = x.replace(/^[وبلكف](?=.{3,})/, "");
  // ⚠ لا نقطع «ون»: هي من أصل كلمات كثيرة — «مخزون» تصير «مخز»
  // و«موردون» تصير «مورد» بالصدفة لا بالقاعدة. نقطع اللواحق الواضحة
  // فقط، وبشرط بقاء ثلاثة أحرف فأكثر.
  // ⚠ مع مجموعة التقاط تصير الوسائط (match, p1, offset, string) —
  // قراءتها خطأً تجعل الشرط دائمًا كاذبًا فلا تُقطع لاحقة أبدًا.
  x = x.replace(/(ين|ات|ها|هم|كم|نا)$/, (m) => (x.length - m.length >= 3 ? "" : m));
  return x;
};

export { stemAr };
