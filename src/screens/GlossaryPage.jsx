function GlossaryPage({ initial = "", onBack }) {
  const [q, setQ] = useState(initial);
  const n = (x) => String(x || "").replace(/[ًٌٍَُِّْـ]/g, "").replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").toLowerCase();
  const hits = TERMS.filter(([t, d, w]) => !q.trim() || n(t + " " + d + " " + w).includes(n(q.trim())));
  return (
    <div>
      <SubPageHeader title="مسرد المصطلحات" onBack={onBack} />
      <div className="px-4 pt-3 pb-8">
        <input style={inputStyle} value={q} onChange={(e) => setQ(e.target.value)} placeholder="ابحث عن مصطلح: عهدة، عربون، في الطريق…" aria-label="بحث المصطلحات" />
        <div className="flex flex-col gap-2 mt-3">
          {hits.length === 0 ? (
            <EmptyState icon={<BookOpen size={36} color="var(--accentText)" />} title="لا مصطلح بهذا البحث" sub="جرّب كلمةً أقصر" />
          ) : hits.map(([t, d, w]) => (
            <Card key={t} style={{ padding: 12 }}>
              <p style={{ color: "var(--text)" }} className="text-[13px] font-bold">{t}</p>
              <p style={{ color: "var(--text2)" }} className="text-[12px] mt-0.5 leading-6">{d}</p>
              <p style={{ color: "var(--text3)" }} className="text-[11px] mt-0.5">أين: {w}</p>
            </Card>
          ))}
        </div>
      </div>
    </div>
  );
}

export { GlossaryPage };
